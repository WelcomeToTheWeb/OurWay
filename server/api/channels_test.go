// 2.4-6: notification channels. The bar is that a channel reaching a mailbox and
// a channel reaching an HTTP endpoint are the same product: the same ledger, the
// same refusal rules, the same audit, the same scope. These requests are console
// requests, and refusals are asserted on the reason the console can name.

func channelsRequest(t *testing.T, ts *httptest.Server, token, method, path string, body string) (int, map[string]interface{}, http.Header) {
	t.Helper()
	req, err := http.NewRequest(method, ts.URL+path, bytes.NewBufferString(body))
	if err != nil {
		t.Fatalf("build request: %v", err)
	}
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Content-Type", "application/json")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("%s %s: %v", method, path, err)
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(resp.Body)
	var payload map[string]interface{}
	if len(bytes.TrimSpace(raw)) > 0 {
		_ = json.Unmarshal(raw, &payload)
	}
	return resp.StatusCode, payload, resp.Header
}

func channelToken(t *testing.T, st *store.Store, jwt *auth.JWTAuth, username string, roles []string, clientID string) string {
	t.Helper()
	user := &models.User{
		ID: uuid.NewString(), Username: username, Email: username + "@corp.example",
		PasswordHash: "x", Status: "active", Provider: "local",
	}
	if err := st.Users.Create(user); err != nil {
		t.Fatalf("create user: %v", err)
	}
	if clientID != "" {
		// Tenant administration is the user-client grant the scope helper reads.
		if err := st.Clients.AddUserClient(user.ID, clientID); err != nil {
			t.Fatalf("grant tenant: %v", err)
		}
	}
	for _, roleName := range roles {
		role, err := st.Roles.GetRoleByName(roleName)
		if err != nil {
			t.Fatalf("role %s: %v", roleName, err)
		}
		if err := st.UserRoles.AssignRole(user.ID, role.ID); err != nil {
			t.Fatalf("assign role: %v", err)
		}
	}
	token, err := jwt.GenerateToken(user.ID, user.Username, roles)
	if err != nil {
		t.Fatalf("token: %v", err)
	}
	return token
}

// A webhook channel is the v2.3 kind with v2.3's defaults.
func TestWebhookChannelNeedsNoKindTalk(t *testing.T) {
	ts, st, jwtAuth := newTestServer(t)
	token := channelToken(t, st, jwtAuth, "ops-admin", []string{"admin"}, "")

	status, body, _ := channelsRequest(t, ts, token, http.MethodPost, "/api/v2/channels", `{
		"name": "fleet hook", "url": "https://hook.invalid/fleet",
		"events": ["alert_created", "patch_deployed"]
	}`)
	if status != http.StatusCreated {
		t.Fatalf("create channel = %d: %v", status, body)
	}
	channel := body["webhook"].(map[string]interface{})
	if channel["kind"] != models.ChannelKindWebhook {
		t.Errorf("kind = %v, want webhook", channel["kind"])
	}
	// The signing secret is generated by the server and shown exactly once, on
	// creation, so the receiver can verify signatures. No read path repeats it.
	secret, _ := body["secret"].(string)
	if len(secret) < 32 {
		t.Fatalf("the creation answer carries no signing secret: %v", body["secret"])
	}
	created, err := st.Webhooks.GetByID(channel["id"].(string))
	if err != nil {
		t.Fatalf("load: %v", err)
	}
	if created.Secret != secret {
		t.Error("the secret the receiver was shown is not the secret that signs")
	}
	_, listed, _ := channelsRequest(t, ts, token, http.MethodGet, "/api/v2/channels", "")
	if strings.Contains(fmt.Sprint(listed), secret) {
		t.Error("the ledger response carries the signing secret")
	}
	_, single, _ := channelsRequest(t, ts, token, http.MethodGet, "/api/v2/channels/"+created.ID, "")
	if strings.Contains(fmt.Sprint(single), secret) {
		t.Error("the channel read carries the signing secret")
	}
}

// Every refusal names the kind's requirement, so the form can say what is
// missing without a dictionary of reason codes.
func TestChannelKindRefusesWhatItsKindCannotDeliver(t *testing.T) {
	ts, st, jwtAuth := newTestServer(t)
	token := channelToken(t, st, jwtAuth, "ops-admin", []string{"admin"}, "")

	cases := []struct {
		name     string
		body     string
		wantText string
	}{
		{"webhook without a URL", `{"name":"no url","kind":"webhook","events":["alert_created"]}`, "url is required for a webhook, slack and teams channel"},
		{"slack without a URL", `{"name":"no url","kind":"slack","events":["alert_created"]}`, "url is required for a webhook, slack and teams channel"},
		{"teams without a URL", `{"name":"no url","kind":"teams","events":["alert_created"]}`, "url is required for a webhook, slack and teams channel"},
		{"email without recipients", `{"name":"no box","kind":"email","events":["alert_created"]}`, "config.to"},
		{"email with a URL", fmt.Sprintf(`{"name":"box with url","kind":"email","events":["alert_created"],"url":"https://hook.invalid/x","config":{"to":["oncall@corp.example"]}}`), "an email channel has no url"},
		{"email with no mail server", `{"name":"box","kind":"email","events":["alert_created"],"config":{"to":["oncall@corp.example"]}}`, "SMTP_HOST"},
		{"unknown severity floor", `{"name":"floor","kind":"webhook","url":"https://hook.invalid/x","events":["alert_created"],"min_severity":"apocalyptic"}`, "info, warning or critical"},
		{"unknown kind", `{"name":"carrier pigeon","kind":"pigeon","url":"https://hook.invalid/x","events":["alert_created"]}`, "webhook, email, slack or teams"},
	}
	for _, tc := range cases {
		status, body, _ := channelsRequest(t, ts, token, http.MethodPost, "/api/v2/channels", tc.body)
		if status != http.StatusBadRequest {
			t.Errorf("%s: status = %d, want 400 (%v)", tc.name, status, body)
			continue
		}
		joined := fmt.Sprint(body["reason"]) + fmt.Sprint(body["error"])
		if !strings.Contains(joined, tc.wantText) {
			t.Errorf("%s: refusal says %q, want it to name %q", tc.name, joined, tc.wantText)
		}
	}
}

// A channel's kind decides what its payload means, and the delivery history is
// read against that meaning. Switching kind on a row is the kind of change that
// silently makes an operator's own alerts unreadable, so it is refused.
func TestChannelKindIsFixedOnceBuilt(t *testing.T) {
	ts, st, jwtAuth := newTestServer(t)
	token := channelToken(t, st, jwtAuth, "ops-admin", []string{"admin"}, "")

	_, created, _ := channelsRequest(t, ts, token, http.MethodPost, "/api/v2/channels",
		`{"name":"hook","kind":"webhook","url":"https://hook.invalid/x","events":["alert_created"]}`)
	id := created["webhook"].(map[string]interface{})["id"].(string)

	status, body, _ := channelsRequest(t, ts, token, http.MethodPut, "/api/v2/channels/"+id, `{"kind":"email"}`)
	if status != http.StatusConflict {
		t.Fatalf("kind change = %d: %v", status, body)
	}
	if !strings.Contains(fmt.Sprint(body["error"]), "kind cannot be changed") {
		t.Errorf("the refusal does not say why: %v", body)
	}
	reloaded, err := st.Webhooks.GetByID(id)
	if err != nil {
		t.Fatalf("load: %v", err)
	}
	if reloaded.Kind != models.ChannelKindWebhook {
		t.Errorf("stored kind = %q, want the kind it was created as", reloaded.Kind)
	}
}

// Tenant scope names the tenant the caller cannot see — the same rule as the
// alert threshold scopes in 2.4-5.
func TestChannelTenantScopeNamesTheTenantTheCallerCannotSee(t *testing.T) {
	ts, st, jwtAuth := newTestServer(t)
	admin := channelToken(t, st, jwtAuth, "ops-admin", []string{"admin"}, "")

	alpha := createChannelClient(t, st, "Alpha Co", "alpha-co")
	beta := createChannelClient(t, st, "Beta Co", "beta-co")
	manager := channelToken(t, st, jwtAuth, "alpha-manager", []string{"manager"}, alpha.ID)

	// A manager defining a channel for a tenant they can see is exactly what
	// 2.4-6 asks of a manager.
	status, created, _ := channelsRequest(t, ts, manager, http.MethodPost, "/api/v2/channels", fmt.Sprintf(
		`{"name":"alpha mailbox","kind":"webhook","url":"https://hook.invalid/alpha","events":["alert_created"],"scope_clients":["%s"]}`, alpha.ID))
	if status != http.StatusCreated {
		t.Fatalf("manager channel = %d: %v", status, created)
	}

	// The same manager cannot define a channel for a tenant they do not administer.
	status, body, _ := channelsRequest(t, ts, manager, http.MethodPost, "/api/v2/channels", fmt.Sprintf(
		`{"name":"beta mailbox","kind":"webhook","url":"https://hook.invalid/beta","events":["alert_created"],"scope_clients":["%s"]}`, beta.ID))
	if status != http.StatusNotFound {
		t.Errorf("out-of-scope tenant = %d: %v, want 404", status, body)
	}

	// A manager defining a channel for **every** tenant is the one channel shape
	// a tenant administrator must not own.
	status, body, _ = channelsRequest(t, ts, manager, http.MethodPost, "/api/v2/channels",
		`{"name":"everything","kind":"webhook","url":"https://hook.invalid/all","events":["alert_created"]}`)
	if status != http.StatusForbidden {
		t.Errorf("all-tenant channel = %d: %v, want 403", status, body)
	}
	if !strings.Contains(fmt.Sprint(body["reason"]), "admin") {
		t.Errorf("refusal does not name who may do it: %v", body)
	}

	// A manager sees only channels that reach their tenants; an admin sees all.
	_, list, _ := channelsRequest(t, ts, manager, http.MethodGet, "/api/v2/channels", "")
	if names := channelNames(list); len(names) != 1 || !strings.Contains(names[0], "alpha") {
		t.Errorf("manager sees %v, want only the channel scoped to their tenant", names)
	}
	_, adminList, _ := channelsRequest(t, ts, admin, http.MethodGet, "/api/v2/channels", "")
	if len(channelNames(adminList)) != 1 {
		t.Errorf("admin sees %v, want the channel the manager created", channelNames(adminList))
	}

	// Roles below manager do not own notification routing.
	for _, role := range []string{"technician", "viewer"} {
		low := channelToken(t, st, jwtAuth, role+"-user", []string{role}, "")
		status, _, _ = channelsRequest(t, ts, low, http.MethodGet, "/api/v2/channels", "")
		if status != http.StatusForbidden {
			t.Errorf("%s reading channels = %d, want 403", role, status)
		}
	}
}

// `/v2/webhooks` and `/v2/channels` are one ledger, not two: a v2.3 integration
// keeps calling the name it knows, and the console calls the name that describes
// what the row now is. A test on the pair is the test that they did not fork.
func TestTheTwoNamesAddressOneLedger(t *testing.T) {
	ts, st, jwtAuth := newTestServer(t)
	admin := channelToken(t, st, jwtAuth, "ops-admin", []string{"admin"}, "")

	_, created, _ := channelsRequest(t, ts, admin, http.MethodPost, "/api/v2/channels",
		`{"name":"pair","kind":"webhook","url":"https://hook.invalid/x","events":["alert_created"]}`)
	id := created["webhook"].(map[string]interface{})["id"].(string)

	for _, path := range []string{"/api/v2/webhooks", "/api/v2/channels"} {
		status, list, _ := channelsRequest(t, ts, admin, http.MethodGet, path, "")
		if status != http.StatusOK {
			t.Fatalf("%s = %d: %v", path, status, list)
		}
		if names := channelNames(list); len(names) != 1 || names[0] != "pair" {
			t.Errorf("%s answers %v, want the same ledger", path, names)
		}
	}

	status, webhookName, _ := channelsRequest(t, ts, admin, http.MethodGet, "/api/v2/webhooks/"+id, "")
	status2, channelName, _ := channelsRequest(t, ts, admin, http.MethodGet, "/api/v2/channels/"+id, "")
	if status != http.StatusOK || status2 != http.StatusOK {
		t.Fatalf("reads by id = %d / %d", status, status2)
	}
	if fmt.Sprint(webhookName) != fmt.Sprint(channelName) {
		t.Errorf("the two names describe the channel differently:\n%v\n%v", webhookName, channelName)
	}
}

// The delivery ledger is the console's answer to "why didn't my phone buzz?".
// It is the same record for every kind.
func TestDeliveryLedgerCarriesTheSameRecordForEveryKind(t *testing.T) {
	ts, st, jwtAuth := newTestServer(t)
	admin := channelToken(t, st, jwtAuth, "ops-admin", []string{"admin"}, "")

	_, created, _ := channelsRequest(t, ts, admin, http.MethodPost, "/api/v2/channels",
		`{"name":"hook","kind":"webhook","url":"https://hook.invalid/x","events":["alert_created"]}`)
	id := created["webhook"].(map[string]interface{})["id"].(string)
	retry := time.Now().Add(2 * time.Minute)

	if err := st.WebhookDeliveries.Create(&models.WebhookDelivery{
		ID: uuid.NewString(), WebhookID: id, Event: "alert_created",
		Payload: `{"type":"alert_created"}`, Status: "pending", Attempts: 2,
		StatusCode: 500, ResponseBody: "endpoint refused", NextRetryAt: &retry,
	}); err != nil {
		t.Fatalf("seed delivery: %v", err)
	}

	status, list, _ := channelsRequest(t, ts, admin, http.MethodGet, "/api/v2/channels/"+id+"/deliveries", "")
	if status != http.StatusOK {
		t.Fatalf("deliveries = %d: %v", status, list)
	}
	rows, _ := list["deliveries"].([]interface{})
	if len(rows) != 1 {
		t.Fatalf("deliveries = %v, want the one row the ledger holds", list)
	}
	row, _ := rows[0].(map[string]interface{})
	if row["kind"] != models.ChannelKindWebhook {
		t.Errorf("ledger row does not name the kind: %v", row)
	}
	if row["event"] != "alert_created" || row["status"] != "pending" {
		t.Errorf("ledger row = %v, want the event and status it records", row)
	}
	if row["attempts"].(float64) != 2 {
		t.Errorf("attempts = %v, want 2", row["attempts"])
	}
	if row["status_code"].(float64) != 500 {
		t.Errorf("status_code = %v, want 500", row["status_code"])
	}
	if row["response_body"] != "endpoint refused" {
		t.Errorf("the ledger does not carry the peer's answer: %v", row["response_body"])
	}
	if row["next_retry_at"] == nil || row["next_retry_at"] == "" {
		t.Errorf("the ledger does not say when the retry happens: %v", row["next_retry_at"])
	}
}

// useTestMailTransport installs a mail transport for one test and puts the
// installation's real one back afterwards.
func useTestMailTransport(t *testing.T, transport webhooks.SMTP) func() {
	t.Helper()
	previous := MailTransport()
	SetMailTransport(transport)
	t.Cleanup(func() { SetMailTransport(previous) })
	return func() { SetMailTransport(previous) }
}

